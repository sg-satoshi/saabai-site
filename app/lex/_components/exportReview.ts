import { Document, Packer, Paragraph, TextRun, Header, Footer, AlignmentType, HeadingLevel } from "docx";
import { type ReviewReport, buildIssues, SEVERITY, RISK_LABEL, axisLabel } from "../../../lib/lex-review-display";

/** Doc review report to .docx: risk summary, issues by severity, recommended actions. Footer keeps "Powered by Saabai.ai". */
export async function exportReviewToWord(opts: { report: ReviewReport; fileName?: string; firmName?: string; comparison?: string }) {
  const { report: r, fileName, firmName, comparison } = opts;
  const para = (text: string, extra: Partial<{ bold: boolean; size: number; color: string; italics: boolean }> = {}) =>
    new Paragraph({ children: text.split("\n").map((line, i) => new TextRun({ text: line, break: i > 0 ? 1 : 0, ...extra })), spacing: { after: 140 } });
  const h2 = (text: string) => new Paragraph({ text, heading: HeadingLevel.HEADING_2, spacing: { before: 240, after: 120 } });
  const issues = buildIssues(r);
  const children: Paragraph[] = [
    new Paragraph({ text: "Document review", heading: HeadingLevel.HEADING_1, spacing: { after: 200 } }),
    para(`${fileName ? fileName + ". " : ""}${r.documentType}. ${r.jurisdiction}.`, { bold: true }),
    para(`Overall risk: ${RISK_LABEL[r.riskLevel] ?? r.riskLevel} (${r.overallScore}/100). ${r.wordCount.toLocaleString("en-AU")} words, ${r.clauseCount} clauses.`),
    h2("Summary"), para(r.summary),
  ];
  if (issues.length) {
    children.push(h2(`Issues (${issues.length})`));
    for (const i of issues) {
      const where = i.clauseRef ? ` (${i.clauseRef})` : "";
      const tag = i.kind === "missing" ? "Missing clause" : i.kind === "legislation" ? "Legislation" : axisLabel(i.axis);
      children.push(para(`${SEVERITY[i.severity].label}. ${tag}. ${i.title}${where}`, { bold: true }));
      children.push(para(i.detail));
      if (i.recommendation) children.push(para(`Recommendation: ${i.recommendation}`));
      if (i.redline) children.push(para(`Suggested redline: ${i.redline}`, { italics: true }));
    }
  }
  if (r.recommendedActions?.length) {
    children.push(h2("Recommended actions"));
    r.recommendedActions.forEach((a, n) => children.push(para(`${n + 1}. ${a}`)));
  }
  if (comparison) { children.push(h2("Comparison with another document")); children.push(...comparison.split(/\n{2,}/).map((p) => para(p))); }
  children.push(para("Review assistance only, not legal advice. Check the document and primary sources before advising a client.", { italics: true, color: "808080", size: 18 }));

  const headerChildren: Paragraph[] = [];
  if (firmName) headerChildren.push(new Paragraph({ children: [new TextRun({ text: firmName, bold: true, size: 20 })], alignment: AlignmentType.LEFT }));
  headerChildren.push(new Paragraph({ children: [new TextRun({ text: "Generated by Lex AI", color: "808080", size: 18 })], alignment: AlignmentType.RIGHT }));
  const date = new Date().toLocaleDateString("en-AU", { timeZone: "Australia/Brisbane" });
  const doc = new Document({
    sections: [{
      properties: {},
      headers: { default: new Header({ children: headerChildren }) },
      footers: { default: new Footer({ children: [new Paragraph({ children: [new TextRun({ text: `${date} \u00b7 Powered by Saabai.ai`, color: "808080", size: 18 })], alignment: AlignmentType.CENTER })] }) },
      children,
    }],
  });
  const blob = await Packer.toBlob(doc);
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `Lex_review_${new Date().toISOString().slice(0, 10)}.docx`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
