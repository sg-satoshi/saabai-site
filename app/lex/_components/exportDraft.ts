import { Document, Packer, Paragraph, TextRun, Header, Footer, AlignmentType } from "docx";

/** Drafted document to .docx. Same layout as before phase C, with the "Powered by Saabai.ai" footer credit. */
export async function exportDraftToWord(opts: { draftText: string; docTypeName: string; jurisdiction: string; firmName?: string }) {
  const { draftText, docTypeName, jurisdiction, firmName } = opts;
  const paragraphs = draftText.split(/\n{2,}/).map((para) =>
    new Paragraph({
      children: para.split("\n").map((line, i) => new TextRun({ text: line, break: i > 0 ? 1 : 0 })),
      spacing: { after: 200 },
    }),
  );

  const headerChildren: Paragraph[] = [];
  if (firmName) headerChildren.push(new Paragraph({ children: [new TextRun({ text: firmName, bold: true, size: 20 })], alignment: AlignmentType.LEFT }));
  headerChildren.push(new Paragraph({ children: [new TextRun({ text: "Generated by Lex AI", color: "808080", size: 18 })], alignment: AlignmentType.RIGHT }));

  const date = new Date().toLocaleDateString("en-AU", { timeZone: "Australia/Brisbane" });
  const doc = new Document({
    sections: [{
      properties: {},
      headers: { default: new Header({ children: headerChildren }) },
      footers: {
        default: new Footer({
          children: [new Paragraph({ children: [new TextRun({ text: `${date} \u00b7 ${jurisdiction} \u00b7 Powered by Saabai.ai`, color: "808080", size: 18 })], alignment: AlignmentType.CENTER })],
        }),
      },
      children: [
        new Paragraph({ children: [new TextRun({ text: docTypeName, bold: true, size: 32 })], spacing: { after: 300 }, alignment: AlignmentType.CENTER }),
        ...paragraphs,
      ],
    }],
  });

  const blob = await Packer.toBlob(doc);
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${docTypeName.replace(/\s+/g, "_")}_${new Date().toISOString().slice(0, 10)}.docx`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
