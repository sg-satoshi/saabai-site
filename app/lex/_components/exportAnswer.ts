import { Document, Packer, Paragraph, TextRun, Header, Footer, AlignmentType, HeadingLevel } from "docx";
import type { LexAnswerMeta } from "../../../lib/lex-sources";
import { plainAnswer, citedSources, STATUS_TEXT } from "../../../lib/lex-cite-display";

/** Research answer to .docx: question, answer with [n] citations, conclusions and a numbered source list. */
export async function exportAnswerToWord(opts: { question: string; answer: string; meta?: LexAnswerMeta; firmName?: string; stamp?: string }) {
  const { question, answer, meta, firmName, stamp } = opts;
  const body = plainAnswer(answer, meta?.citations ?? []);
  const para = (text: string, extra: Partial<{ bold: boolean; size: number; color: string; italics: boolean }> = {}) =>
    new Paragraph({ children: text.split("\n").map((line, i) => new TextRun({ text: line, break: i > 0 ? 1 : 0, ...extra })), spacing: { after: 160 } });

  const children: Paragraph[] = [
    new Paragraph({ text: "Research note", heading: HeadingLevel.HEADING_1, spacing: { after: 200 } }),
    para(`Question: ${question}`, { bold: true }),
    ...(stamp ? [para(`Searched ${stamp}`, { color: "808080", size: 18 })] : []),
    ...body.split(/\n{2,}/).map((p) => para(p)),
  ];
  if (meta?.conclusions.length) {
    children.push(new Paragraph({ text: "Conclusions", heading: HeadingLevel.HEADING_2, spacing: { before: 240, after: 120 } }));
    for (const c of meta.conclusions) children.push(para(`${c.confidence[0].toUpperCase()}${c.confidence.slice(1)} confidence: ${c.text}${c.basis ? ` (${c.basis})` : ""}`));
  }
  const cited = meta ? citedSources(meta).cited : [];
  if (cited.length) {
    children.push(new Paragraph({ text: "Sources", heading: HeadingLevel.HEADING_2, spacing: { before: 240, after: 120 } }));
    for (const s of cited) children.push(para(`[${s.n}] ${s.title}. ${s.typeLabel}. ${STATUS_TEXT[s.status].label}. ${s.url}`, { size: 20 }));
  }
  children.push(para("Research assistance only, not legal advice. Check primary sources before advising a client.", { italics: true, color: "808080", size: 18 }));

  const headerChildren: Paragraph[] = [];
  if (firmName) headerChildren.push(new Paragraph({ children: [new TextRun({ text: firmName, bold: true, size: 20 })], alignment: AlignmentType.LEFT }));
  headerChildren.push(new Paragraph({ children: [new TextRun({ text: "Generated by Lex AI", color: "808080", size: 18 })], alignment: AlignmentType.RIGHT }));

  const doc = new Document({
    sections: [{
      properties: {},
      headers: { default: new Header({ children: headerChildren }) },
      footers: {
        default: new Footer({
          children: [new Paragraph({ children: [new TextRun({ text: `${new Date().toLocaleDateString("en-AU", { timeZone: "Australia/Brisbane" })} \u00b7 Powered by Saabai.ai`, color: "808080", size: 18 })], alignment: AlignmentType.CENTER })],
        }),
      },
      children,
    }],
  });
  const blob = await Packer.toBlob(doc);
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `Lex_research_${new Date().toISOString().slice(0, 10)}.docx`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
