#!/usr/bin/env node
// Builds lib/lex-help-content.generated.ts from content/lex-help/*.md. `--check` exits 1 if stale.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
const dir = "content/lex-help", out = "lib/lex-help-content.generated.ts";
const docs = readdirSync(dir).filter((f) => f.endsWith(".md") && f !== "README.md").sort().map((f) => {
  const raw = readFileSync(`${dir}/${f}`, "utf8");
  const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`${f}: missing front matter`);
  const fm = Object.fromEntries(m[1].split("\n").map((l) => { const i = l.indexOf(":"); return [l.slice(0, i).trim(), l.slice(i + 1).trim()]; }));
  if (!fm.title) throw new Error(`${f}: title required`);
  const list = (s) => (s || "").split(/[,\s]+/).map((x) => x.trim()).filter(Boolean);
  return { id: f.replace(/\.md$/, ""), title: fm.title, routes: list(fm.routes), keywords: list(fm.keywords), body: m[2].trim() };
});
const text = `// GENERATED by scripts/build-lex-help.mjs from content/lex-help/*.md. Do not edit.\nexport const LEX_HELP_DOCS: { id: string; title: string; routes: string[]; keywords: string[]; body: string }[] = ${JSON.stringify(docs, null, 2)};\n`;
if (process.argv.includes("--check")) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) { console.error(`${out} is stale: run node scripts/build-lex-help.mjs`); process.exit(1); }
  console.log("lex help content: ok");
} else { writeFileSync(out, text); console.log(`wrote ${out} (${docs.length} docs)`); }
